CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE users (
    id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    google_sub   TEXT        NOT NULL UNIQUE,
    email        TEXT        NOT NULL,
    display_name TEXT        NOT NULL,
    avatar_url   TEXT,
    username     CITEXT      NOT NULL UNIQUE
                 CHECK (username ~ '^[a-zA-Z0-9_]{3,32}$'),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX users_username_prefix_idx ON users (lower(username::text) text_pattern_ops);

CREATE TABLE sessions (
    token_hash BYTEA       PRIMARY KEY, -- SHA-256 of the cookie token; raw token never stored
    user_id    BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX sessions_user_id_idx ON sessions (user_id);
CREATE INDEX sessions_expires_at_idx ON sessions (expires_at);

CREATE TABLE conversations (
    id              BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    -- Canonical "<minUserID>:<maxUserID>" so a pair of users maps to exactly one DM.
    direct_key      TEXT        NOT NULL UNIQUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_message_at TIMESTAMPTZ
);
CREATE INDEX conversations_last_message_at_idx ON conversations (last_message_at DESC);

CREATE TABLE conversation_members (
    conversation_id      BIGINT      NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    user_id              BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    last_read_message_id BIGINT,
    joined_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (conversation_id, user_id)
);
CREATE INDEX conversation_members_user_id_idx ON conversation_members (user_id);

CREATE TABLE messages (
    id                BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    conversation_id   BIGINT      NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    sender_id         BIGINT      NOT NULL REFERENCES users(id),
    client_message_id UUID        NOT NULL, -- idempotency key generated by the client
    body              TEXT        NOT NULL CHECK (char_length(body) BETWEEN 1 AND 4000),
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (sender_id, client_message_id)
);
CREATE INDEX messages_conversation_id_id_idx ON messages (conversation_id, id DESC);
